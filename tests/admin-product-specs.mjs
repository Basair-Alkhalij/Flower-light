import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const window={FLOWER_LIGHT_CUSTOM_FILTERS:[]};
vm.runInNewContext(fs.readFileSync(new URL('../admin-product-specs.js',import.meta.url),'utf8'),{window});
const specs=window.FL_ADMIN_PRODUCT_SPECS;
assert.equal(specs.PRODUCT_SPEC_FIELDS.length,15);
assert.equal(specs.resolveProductSpecDefinition('الواط').key,'wattage');
assert.equal(specs.resolveProductSpecDefinition('درجة الحماية').key,'ip_rating');
assert.equal(specs.resolveProductSpecDefinition('power').key,'wattage');
assert.equal(specs.resolveProductSpecDefinition('not-known'),null);
window.FLOWER_LIGHT_CUSTOM_FILTERS=[{key:'custom_filter_mount',label:'نوع التركيب'},{key:'custom_filter_mount',label:'مكرر'},{key:'bad*key',label:'غير صالح'}];
assert.ok(specs.productSpecFields().some(row=>row.key==='custom_filter_mount'));
assert.equal(specs.productSpecFields().filter(row=>row.key==='custom_filter_mount').length,1);
assert.equal(specs.resolveProductSpecDefinition('custom_filter_mount').label,'نوع التركيب');
const normalized=specs.normalizeKnownSpecValue('12W',{unit:'W'},'');
assert.equal(normalized.value,'12');
assert.equal(normalized.unit,'W');
console.log('ADMIN_PRODUCT_SPECS_MODULE_OK');
